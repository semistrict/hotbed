// Command protoc-gen-hotbed-hooks makes, for each proto file with services,
// a Go package (hotbedv1cli for hotbed/v1) of what the client needs to make
// its commands: the API's descriptors, comments and all, and Hooks, an
// interface of every Go hook its commands name, which the client
// implements (var _ Hooks = ...), so a hook named in the proto and not
// written in Go fails the build.
package main

import (
	"fmt"
	"path"
	"slices"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"

	"github.com/semistrict/hotbed/internal/apicmd/spec"
)

const (
	apicmdPackage = protogen.GoImportPath("github.com/semistrict/hotbed/internal/apicmd")
	contextPkg    = protogen.GoImportPath("context")
	protoPkg      = protogen.GoImportPath("google.golang.org/protobuf/proto")
)

func main() {
	protogen.Options{}.Run(run)
}

// run makes the hooks and descriptors of the one file with services.
func run(gen *protogen.Plugin) error {
	gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
	// Deterministic: the options' extensions, which this binary knows,
	// would otherwise come out in a different order each run.
	descriptors, err := proto.MarshalOptions{Deterministic: true}.Marshal(&descriptorpb.FileDescriptorSet{File: gen.Request.ProtoFile})
	if err != nil {
		return err
	}
	schema, err := spec.Load(descriptors)
	if err != nil {
		return err
	}
	// One package's hooks and descriptors: those of the one file with
	// services, which is all hotbed has.
	var withServices []*protogen.File
	for _, f := range gen.Files {
		if f.Generate && len(f.Services) > 0 {
			withServices = append(withServices, f)
		}
	}
	if len(withServices) > 1 {
		return fmt.Errorf("services in %d files: hooks are made for one", len(withServices))
	}
	for _, f := range withServices {
		generate(gen, f, descriptors, schema, goIdentsFrom(gen))
	}
	return nil
}

// goIdents is every message and enum's Go name, by full name.
type goIdents map[protoreflect.FullName]protogen.GoIdent

func (ids goIdents) addMessages(ms []*protogen.Message) {
	for _, m := range ms {
		ids[m.Desc.FullName()] = m.GoIdent
		for _, e := range m.Enums {
			ids[e.Desc.FullName()] = e.GoIdent
		}
		ids.addMessages(m.Messages)
	}
}

func goIdentsFrom(gen *protogen.Plugin) goIdents {
	ids := goIdents{}
	for _, f := range gen.Files {
		for _, e := range f.Enums {
			ids[e.Desc.FullName()] = e.GoIdent
		}
		ids.addMessages(f.Messages)
	}
	return ids
}

func generate(gen *protogen.Plugin, f *protogen.File, descriptors []byte, schema *spec.Schema, ids goIdents) {
	pkg := protogen.GoPackageName(string(f.GoPackageName) + "cli")
	dir := path.Join(path.Dir(f.GeneratedFilenamePrefix), string(pkg))
	importPath := protogen.GoImportPath(path.Join(string(f.GoImportPath), string(pkg)))

	bin := gen.NewGeneratedFile(path.Join(dir, "descriptors.binpb"), importPath)
	if _, err := bin.Write(descriptors); err != nil {
		gen.Error(err)
		return
	}

	g := gen.NewGeneratedFile(path.Join(dir, path.Base(f.GeneratedFilenamePrefix)+".cli.go"), importPath)
	g.P("// Code generated by protoc-gen-hotbed-hooks. DO NOT EDIT.")
	g.P()
	g.P("// Package ", pkg, " is what the client needs to make ", f.Desc.Package(), "'s commands and")
	g.P("// tools: the API's descriptors, with their comments, and the Go hooks the")
	g.P("// commands name.")
	g.P("package ", pkg)
	g.P()
	g.Import("embed")
	g.P("// Descriptors is the API's FileDescriptorSet, with source info.")
	g.P("//")
	g.P("//go:embed descriptors.binpb")
	g.P("var Descriptors []byte")
	g.P()

	names := make([]string, 0, len(schema.Hooks))
	for name := range schema.Hooks {
		names = append(names, name)
	}
	slices.Sort(names)

	call := g.QualifiedGoIdent(apicmdPackage.Ident("Call"))
	ctx := g.QualifiedGoIdent(contextPkg.Ident("Context"))
	msg := func(d protoreflect.MessageDescriptor) string { return "*" + g.QualifiedGoIdent(ids[d.FullName()]) }

	g.P("// Hooks is every Go hook ", f.Desc.Package(), "'s commands name.")
	g.P("type Hooks interface {")
	for _, name := range names {
		h := schema.Hooks[name]
		uses := strings.Join(h.Uses, ", ")
		switch h.Kind {
		case spec.FieldHook:
			g.P("// ", name, " fills in ", h.Field.FullName(), " (", uses, ").")
			g.P(name, "(ctx ", ctx, ", c *", call, ", req ", msg(h.Request), ") (", goType(g, ids, h.Field), ", error)")
		case spec.InputHook:
			g.P("// ", name, " reads the JSON of ", uses, ".")
			g.P(name, "(ctx ", ctx, ", c *", call, ", input []byte) (", msg(h.Result), ", error)")
		case spec.BeforeHook:
			g.P("// ", name, " runs before ", uses, ", and may change its request.")
			g.P(name, "(ctx ", ctx, ", c *", call, ", req ", msg(h.Request), ") error")
		case spec.AfterHook:
			g.P("// ", name, " runs after ", uses, ".")
			g.P(name, "(ctx ", ctx, ", c *", call, ", req ", msg(h.Request), ", res ", msg(h.Response), ") error")
		}
	}
	g.P("}")
	g.P()

	protoMsg := g.QualifiedGoIdent(protoPkg.Ident("Message"))
	g.P("// Table is h's hooks by the names the commands give them.")
	g.P("func Table(h Hooks) ", g.QualifiedGoIdent(apicmdPackage.Ident("Hooks")), " {")
	g.P("t := ", g.QualifiedGoIdent(apicmdPackage.Ident("NewHooks")), "()")
	for _, name := range names {
		h := schema.Hooks[name]
		switch h.Kind {
		case spec.FieldHook:
			g.P("t.Fields[", fmt.Sprintf("%q", name), "] = func(ctx ", ctx, ", c *", call, ", req ", protoMsg, ") (any, error) {")
			g.P("return h.", name, "(ctx, c, req.(", msg(h.Request), "))")
		case spec.InputHook:
			g.P("t.Inputs[", fmt.Sprintf("%q", name), "] = func(ctx ", ctx, ", c *", call, ", input []byte) (", protoMsg, ", error) {")
			g.P("return h.", name, "(ctx, c, input)")
		case spec.BeforeHook:
			g.P("t.Before[", fmt.Sprintf("%q", name), "] = func(ctx ", ctx, ", c *", call, ", req ", protoMsg, ") error {")
			g.P("return h.", name, "(ctx, c, req.(", msg(h.Request), "))")
		case spec.AfterHook:
			g.P("t.After[", fmt.Sprintf("%q", name), "] = func(ctx ", ctx, ", c *", call, ", req, res ", protoMsg, ") error {")
			g.P("return h.", name, "(ctx, c, req.(", msg(h.Request), "), res.(", msg(h.Response), "))")
		}
		g.P("}")
	}
	g.P("return t")
	g.P("}")
}

// goType is the Go type of a field's value.
func goType(g *protogen.GeneratedFile, ids goIdents, f protoreflect.FieldDescriptor) string {
	var t string
	switch f.Kind() {
	case protoreflect.BoolKind:
		t = "bool"
	case protoreflect.StringKind:
		t = "string"
	case protoreflect.BytesKind:
		t = "[]byte"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		t = "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		t = "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		t = "uint32"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		t = "uint64"
	case protoreflect.FloatKind:
		t = "float32"
	case protoreflect.DoubleKind:
		t = "float64"
	case protoreflect.EnumKind:
		t = g.QualifiedGoIdent(ids[f.Enum().FullName()])
	case protoreflect.MessageKind, protoreflect.GroupKind:
		t = "*" + g.QualifiedGoIdent(ids[f.Message().FullName()])
	}
	if f.IsList() {
		return "[]" + t
	}
	return t
}
