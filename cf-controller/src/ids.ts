export function generatePetname(): string {
	const buf = new Uint32Array(2);
	crypto.getRandomValues(buf);
	const adj = ADJECTIVES[buf[0] % ADJECTIVES.length];
	const noun = NOUNS[buf[1] % NOUNS.length];
	return `${adj}-${noun}`;
}
